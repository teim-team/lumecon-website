/**
 * Generate the internal onboarding resources from the same module /start
 * renders, so the website, the call and the coordinator brief cannot drift.
 *
 *   node scripts/docs/export-plan.mjs      (npm run docs:plan)
 *
 * Writes:
 *   docs/onboarding/plan-your-first-analysis.md  full internal guide,
 *       including the branching rules and the four worked cases the
 *       economics team reviews.
 *   docs/onboarding/coordinator-brief.md         six short sections an
 *       internal coordinator can paste into a deck and send round.
 *
 * Both are generated. Edit src/data/planFirstAnalysis.js and rerun.
 */
