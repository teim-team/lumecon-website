const TIERS = [
  ['begin', 'Needed to begin'],
  ['refine', 'Useful for refining or extending'],
  ['later', 'Optional, for later questions'],
];

function optionLine(o) {
  return o.note ? `${o.label} (${o.note})` : o.label;
}

/* ------------------------------ the guide ------------------------------ */

function guide() {
  const out = [];
  out.push('# Plan your first analysis: the internal guide', '', GENERATED, '');
  out.push(
    'This is the long version, for economists and anyone running an onboarding',
    'call. The public surface is deliberately shorter. The rule this exists to',
    'serve: introduce questions as they become relevant, rather than putting the',
    'whole possible project in front of an organization before a small starting',
    'scope has been agreed.',
    '',
    '**Two dimensions, read separately.** Organizational complexity covers',
    'multiple entities, work locations, states, industries, transactions between',
    'entities, federal contracting and the links between enterprises and a',
    'government. Data readiness covers whether records are centralized,',
    'reachable, consistently defined, geographically identifiable and approved',
    'for sharing. A complex organization frequently has excellent records. A',
    'single-location organization frequently cannot reach its own. Neither',
    'dimension assigns anyone to an advanced onboarding path, and they are never',
    'combined into one score.',
    '',
  );

  out.push('## 1. The questions', '');
  out.push(
    'Four fixed stages, so the end never moves while somebody is working.',
    'Follow-ups sit inside the stage of the question that opens them, and are',
    'asked only where the answer changes the proposed scope or the records',
    'requested.',
    '',
  );
  for (const stage of STAGES) {
    if (!stage.screens.length) continue;
    out.push(`### Stage: ${stage.label}`, '');
    for (const screen of SCREENS.filter((s) => s.stage === stage.id)) {
      if (screen.follow) {
        const f = screen.follow;
        out.push(`#### Follow-up: ${f.label}`, '');
        out.push(`**Asked when.** \`${f.showWhen.toString().replace(/\s+/g, ' ')}\``, '');
        out.push(`**Why it changes the scope.** ${f.purpose}`, '');
        for (const o of f.options) out.push(`- ${optionLine(o)}`);
        out.push('');
        continue;
      }
      for (const q of screen.questions) {
        out.push(`#### ${q.label}`, '');
        out.push(`**Purpose.** ${q.purpose}`, '');
        if (q.help) out.push(`_Shown to the person: ${q.help}_`, '');
        out.push(`_Answer type: ${q.kind === 'multi' ? 'choose any' : 'choose one'}._`, '');
        for (const o of q.options) out.push(`- ${optionLine(o)}`);
        out.push('');
      }
    }
  }

  out.push(
    '## 2. What more information makes possible',
    '',
    'Provisional. Every row needs economist review before it becomes a public',
    'claim, and the rows flagged below are the ones to start with. Read the',
    'benefit column as a change in method, never as a change in the size of the',
    'estimate: better information can move an estimate in either direction,',
    'narrow what the analysis can support, or reveal double counting.',
    '',
    '| What it lets you ask | Information | Analytical benefit | Status | Review |',
    '|---|---|---|---|---|',
  );
  for (const row of CAPABILITY_MATRIX) {
    const benefit = row.note ? `${row.benefit} _${row.note}_` : row.benefit;
    out.push(
      `| ${row.question} | ${row.information} | ${benefit} | ${STATUS[row.status]} | ${row.review ? '**Needs sign-off**' : 'Settled'} |`,
    );
  }
  out.push('');

  out.push(
    '## 3. The records catalog',
    '',
    'Recognizable existing reports, never a request to build a spreadsheet. An',
    'empty alternative means no substitute has been validated, so it is a',
    'question for the call rather than a blank to fill in.',
    '',
    '| Record | Why it matters | Validated alternative | Usually held by |',
    '|---|---|---|---|',
  );
  for (const r of Object.values(RECORDS)) {
    out.push(`| ${r.what} | ${r.why} | ${r.alternative || '_none validated_' } | ${r.holder} |`);
  }
  out.push('');
  out.push(
    'Which category a record falls into depends on the scope. Something optional',
    'for one analysis is essential for another, so the tiering is computed from',
    'the answers rather than fixed to the record.',
    '',
  );

  out.push('## 4. The call', '');
  out.push('It ends with four things settled and nothing else:', '');
  for (const o of CALL_OUTCOMES) out.push(`- **${o.label}.** ${o.detail}`);
  out.push('', 'Thirty minutes:', '');
  for (const slot of CALL_OUTLINE) out.push(`- **${slot.minutes} min, ${slot.title}.** ${slot.detail}`);
  out.push('', 'Standing notes:', '');
  for (const n of CALL_NOTES) out.push(`- ${n}`);
  out.push('');

  out.push(
    '## 5. Reporting coverage',
    '',
    'Factual indicators only. Each names what it measures and the denominator it',
    'needs, and is shown only where that denominator is known. Geographic',
    'coverage says nothing about whether the model is right. Sensitivity or',
    'scenario ranges are a separate thing again, and statistical confidence',
    'intervals need a separately justified methodology.',
    '',
    '| Indicator | What it measures | Denominator |',
    '|---|---|---|',
  );
  for (const c of COVERAGE_INDICATORS) {
    out.push(`| ${c.label} | ${c.measures} | ${c.denominator} |`);
  }
  out.push(
    '',
    'Preferred phrasing: "this replaces an assumed allocation with your observed',
    'spending". Not: "this improves confidence by 20 percent".',
    '',
  );

  out.push(
    '## 6. Open with the economics team',
    '',
    'Treat the matrix and the branching rules as provisional until these are',
    'answered.',
    '',
  );
  for (const q of OPEN_METHODOLOGY_QUESTIONS) {
    out.push(`- **${q.question}**  `, `  Blocks: ${q.blocks}`);
  }
  out.push('');

  out.push(
    '## 7. Worked cases',
    '',
    'Generated by running the real logic over each set of answers. This is what',
    'the flow actually produces, so it is the thing to review.',
    '',
  );
  for (const c of CASES) {
    const plan = derivePlan(c.answers);
    out.push(`### ${c.name}`, '');
    out.push('```', JSON.stringify(c.answers, null, 2), '```', '');
    if (!plan.confidence.sufficient) {
      out.push(`**Recommendation.** ${plan.confidence.reason}`, '');
    } else {
      out.push(`**Proposed scope.** ${plan.scope.sentence}`, '');
      for (const b of plan.scope.bounds) out.push(`- ${b}`);
      out.push('');
      if (plan.confidence.caveat) out.push(`_${plan.confidence.caveat}_`, '');
    }
    out.push(
      `**Structure.** ${plan.structure.label}` +
        (plan.structure.signals.length ? ` (${plan.structure.signals.join('; ')})` : ''),
      '',
      `**Records.** ${plan.records.label}` +
        (plan.records.notes.length ? ` (${plan.records.notes.join(' ')})` : ''),
      '',
    );
    if (plan.firstOutput.notYet.length) {
      out.push('**Will not show yet.**', '');
      for (const n of plan.firstOutput.notYet) out.push(`- ${n}`);
      out.push('');
    }
    for (const [key, label] of TIERS) {
      const rows = plan.checklist.filter((r) => r.tier === key);
      if (!rows.length) continue;
      out.push(`**${label}.**`, '');
      for (const r of rows) out.push(`- ${r.what}. ${r.why} _(${r.holder})_`);
      out.push('');
    }
    out.push('**Who needs to help.**', '');
    for (const p of plan.participants) out.push(`- ${p.role}. ${p.why}`);
    out.push('');
    if (plan.openQuestions.length) {
      out.push('**To settle on the call.**', '');
      for (const q of plan.openQuestions) out.push(`- ${q}`);
      out.push('');
    }
  }

  return out.join('\n').replace(/\n{3,}/g, '\n\n') + '\n';
}

/* ------------------------- the coordinator brief ------------------------ */

function brief() {
  const out = [];
  out.push('# Planning a first economic analysis', '', GENERATED, '');
  out.push(
    'For the person inside an organization who has to explain to colleagues what',
    'this involves. Six short sections, one per slide. Nothing here commits the',
    'organization to anything beyond a thirty-minute call.',
    '',
  );

  out.push(
    '## 1. What we are doing',
    '',
    'Estimating what our activity supports in the regional economy: jobs, labor',
    'income, value added and economic output, with direct, indirect and induced',
    'effects reported separately.',
    '',
    'We are starting with one analysis, not with everything we could eventually',
    'measure. One boundary, one region, one reporting year.',
    '',
  );

  out.push(
    '## 2. What it needs from us to begin',
    '',
    'A defined activity, a year, a geography and an operating measure in dollars,',
    'plus payroll and a headcount. In practice that is a financial statement or',
    'an adopted budget, a payroll summary and an employee count, for the same',
    'year.',
    '',
    'Existing reports are what is wanted. Nobody needs to build a spreadsheet,',
    'and nothing should be reformatted before someone has looked at it.',
    '',
  );

  out.push('## 3. What else exists, and what each one adds', '');
  for (const row of CAPABILITY_MATRIX.filter((r) => r.id !== 'baseline')) {
    /* Anything not available today says so in the same breath, so nobody
       carries a promise back to their colleagues that the product does not
       keep. */
    const tag = row.status === 'available' ? '' : ` _(${STATUS[row.status].toLowerCase()})_`;
    out.push(`- **${row.information}.**${tag} ${row.benefit}`);
  }
  out.push(
    '',
    'More information does not automatically mean a larger number. It can move an',
    'estimate in either direction, narrow what we can support, or show where',
    'something was being counted twice.',
    '',
  );

  out.push('## 4. Who we need', '');
  out.push(
    '- Someone who can pull the financial statements.',
    '- Someone who can pull payroll and headcount.',
    '- Someone who can approve sharing records outside the organization.',
    '- Where records sit in different offices, one person tracking who has been asked.',
    '',
    'Not every department, and not senior leadership at every call. People join',
    'when the open questions need them.',
    '',
  );

  out.push('## 5. The call', '');
  for (const slot of CALL_OUTLINE) out.push(`- **${slot.minutes} min.** ${slot.title}. ${slot.detail}`);
  out.push('', 'We leave with:', '');
  for (const o of CALL_OUTCOMES) out.push(`- ${o.label}.`);
  out.push('');

  out.push(
    '## 6. What we will be told honestly',
    '',
    'What the first analysis can report, and what it cannot report yet. Which',
    'figures are observed, which are estimated and which are missing. Coverage is',
    'reported as counts and shares against a stated total, and there is no',
    'confidence score.',
    '',
    'Records are shared inside the product, where access is controlled. Nothing',
    'sensitive goes through a web form or an email attachment.',
    '',
  );

  return out.join('\n').replace(/\n{3,}/g, '\n\n') + '\n';
}

mkdirSync(outDir, { recursive: true });
writeFileSync(resolve(outDir, 'plan-your-first-analysis.md'), guide());
writeFileSync(resolve(outDir, 'coordinator-brief.md'), brief());
console.log('Wrote docs/onboarding/plan-your-first-analysis.md and docs/onboarding/coordinator-brief.md');
